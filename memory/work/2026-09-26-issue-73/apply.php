function gn73_append_once($id, $marker, $html) {
    $post = get_post($id);
    if (!$post) return ['ID' => $id, 'error' => 'missing'];
    $before = (string) $post->post_content;
    if (strpos($before, $marker) !== false) {
        return ['ID' => $id, 'status' => 'already_present', 'hash' => hash('sha256', $before)];
    }
    $after = rtrim($before) . "

" . $html . "
";
    $updated = wp_update_post(['ID' => $id, 'post_content' => $after], true);
    if (is_wp_error($updated)) return ['ID' => $id, 'error' => $updated->get_error_message()];
    return [
        'ID' => $id,
        'status' => 'updated',
        'before_hash' => hash('sha256', $before),
        'after_hash' => hash('sha256', $after),
    ];
}

